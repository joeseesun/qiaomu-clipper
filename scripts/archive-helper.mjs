import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { root } = require('./build-layout.cjs');
const { sourceState, digest } = require('./build-info.cjs');
const [file, version, provenance] = process.argv.slice(2);
if (!file || !/^\d+\.\d+\.\d+$/.test(version || '') || !provenance) throw new Error('Expected package, helper version and pre-build provenance');
const source = JSON.parse(fs.readFileSync(provenance, 'utf8'));
const current = sourceState();
if (source.sourceHash !== current.sourceHash || source.commit !== current.commit) throw new Error('Source changed during helper build');
const sha256 = digest(fs.readFileSync(file));
const destination = path.join(root, 'releases', 'helper', version, sha256.slice(0, 16));
if (fs.existsSync(destination)) throw new Error('Helper archive already exists: ' + destination);
const check = (command, args) => { try { execFileSync(command, args, { stdio: 'pipe' }); return true; } catch { return false; } };
const signed = check('pkgutil', ['--check-signature', file]);
const notarized = signed && check('xcrun', ['stapler', 'validate', file]) && check('spctl', ['--assess', '--type', 'install', file]);
fs.mkdirSync(destination, { recursive: true });
const name = `qiaomu-clipper-helper-${version}.pkg`;
fs.copyFileSync(file, path.join(destination, name), fs.constants.COPYFILE_EXCL);
fs.copyFileSync(file, path.join(destination, 'qiaomu-clipper-helper.pkg'), fs.constants.COPYFILE_EXCL);
fs.writeFileSync(path.join(destination, 'SHA256SUMS'), `${sha256}  ${name}\n${sha256}  qiaomu-clipper-helper.pkg\n`);
fs.writeFileSync(path.join(destination, 'release.json'), JSON.stringify({ schema: 1, component: 'helper', version, ...source, signed, notarized, status: notarized && !source.dirty ? 'ready-for-review' : 'testing-only', published: false }, null, 2) + '\n');
console.log(destination);
